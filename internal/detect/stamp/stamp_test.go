func TestCommentAfterStringStillFlagged(t *testing.T) {
	if _, err := rules.Load(); err != nil {
		t.Fatal(err)
	}
	src := []byte("package p\nvar x = \"ok\" // Sure, here's a helper\n")
	fs, err := Detector{}.Scan(context.Background(), domain.Unit{Path: "a.go", Bytes: src})
	if err != nil {
		t.Fatal(err)
	}
	found := false
	for _, f := range fs {
		if f.RuleID == "stamp.ai_boilerplate" {
			found = true
		}
	}
	if !found {
		t.Fatalf("comment after string missed: %#v", fs)
	}
}

