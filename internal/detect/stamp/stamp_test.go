func TestCoAuthoredAndBoilerplate(t *testing.T) {
	if _, err := rules.Load(); err != nil {
		t.Fatal(err)
	}
	src := []byte("package p\n\n// Co-authored-by: Cursor <cursor@example.com>\n// Sure, here's a helper\n")
	fs, err := Detector{}.Scan(context.Background(), domain.Unit{Path: "a.go", Bytes: src})
	if err != nil {
		t.Fatal(err)
	}
	var co, boil bool
	for _, f := range fs {
		if f.RuleID == "stamp.co_authored_by_ai" {
			co = true
		}
		if f.RuleID == "stamp.ai_boilerplate" {
			boil = true
		}
	}
	if !co || !boil {
		t.Fatalf("co=%v boil=%v %#v", co, boil, fs)
	}
}

func TestAllowProtoc(t *testing.T) {
	if _, err := rules.Load(); err != nil {
		t.Fatal(err)
	}
	src := []byte("// Code generated by protoc-gen-go. DO NOT EDIT.\npackage pb\n")
	fs, err := Detector{}.Scan(context.Background(), domain.Unit{Path: "x.pb.go", Bytes: src})
	if err != nil {
		t.Fatal(err)
	}
	for _, f := range fs {
		if f.RuleID == "stamp.generated_by_ai" || f.RuleID == "stamp.ai_generated" {
			t.Fatalf("protoc flagged: %+v", f)
		}
	}
}

